// Inventory of every timer, random call and wall-clock read in server/shared code (MVP 0 audit).
//   tsx scripts/audit-nondeterminism.ts            print summary
//   tsx scripts/audit-nondeterminism.ts --write    also write docs/baseline/NONDETERMINISM_AUDIT.md
import fs from "node:fs";
import path from "node:path";

const PATTERNS: Record<string, RegExp> = {
  "interval": /\bsetInterval\s*\(/,
  "timeout": /\bsetTimeout\s*\(/,
  "random": /\bMath\.random\s*\(/,
  "wall-clock": /\bDate\.now\s*\(|\bnew Date\s*\(/,
};
const ROOTS = ["src/server", "src/shared"];

function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".ts") ? [path.join(dir, e.name)] : []));
}

const hits: { file: string; line: number; kind: string; text: string }[] = [];
for (const f of ROOTS.flatMap(walk).sort()) {
  fs.readFileSync(f, "utf8").split("\n").forEach((text, i) => {
    for (const [kind, re] of Object.entries(PATTERNS)) if (re.test(text)) hits.push({ file: f, line: i + 1, kind, text: text.trim().slice(0, 140) });
  });
}

const kinds = Object.keys(PATTERNS);
const byFile = new Map<string, Record<string, number>>();
for (const h of hits) { const r = byFile.get(h.file) ?? Object.fromEntries(kinds.map((k) => [k, 0])); r[h.kind]++; byFile.set(h.file, r); }

const total = Object.fromEntries(kinds.map((k) => [k, hits.filter((h) => h.kind === k).length]));
console.log("totals:", total);
for (const [f, r] of [...byFile].sort()) console.log(f.padEnd(34), kinds.map((k) => `${k}=${r[k]}`).join(" "));

if (process.argv.includes("--write")) {
  const out = [
    "# Non-determinism audit (MVP 0)", "",
    `Generated by \`scripts/audit-nondeterminism.ts\` from the working tree on ${new Date().toISOString().slice(0, 10)}. Scope: \`${ROOTS.join("`, `")}\`. Regenerate rather than edit.`, "",
    "Each hit must be migrated to simulation time / seeded streams (authoritative), or documented as operational wall-time (API timeouts, budget windows, UI).", "",
    "## Totals", "", "| Kind | Count |", "|---|---|", ...kinds.map((k) => `| ${k} | ${total[k]} |`), "",
    "## By file", "", `| File | ${kinds.join(" | ")} |`, `|---|${kinds.map(() => "---").join("|")}|`,
    ...[...byFile].sort().map(([f, r]) => `| \`${f}\` | ${kinds.map((k) => r[k] || "").join(" | ")} |`), "",
    "## Every occurrence", "", "| Location | Kind | Line |", "|---|---|---|",
    ...hits.map((h) => `| \`${h.file}:${h.line}\` | ${h.kind} | \`${h.text.replace(/\|/g, "\\|")}\` |`), "",
  ].join("\n");
  fs.mkdirSync("docs/baseline", { recursive: true });
  fs.writeFileSync("docs/baseline/NONDETERMINISM_AUDIT.md", out);
  console.log("wrote docs/baseline/NONDETERMINISM_AUDIT.md");
}
